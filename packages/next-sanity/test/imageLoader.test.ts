test('rounds the proportional height to the nearest integer', () => {
  const result = imageLoader({
    src: 'https://cdn.sanity.io/images/project/dataset/image.jpg?w=1000&h=333',
    width: 828,
    quality: undefined,
  })

  // 333 / 1000 * 828 = 275.724
  expect(result).toBe(
    'https://cdn.sanity.io/images/project/dataset/image.jpg?w=828&h=276&auto=format&fit=min',
  )
})

